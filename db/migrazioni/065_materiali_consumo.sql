-- Materiali di consumo (Adriano 3/11/2026): lamine serigrafiche, pasta saldante, barre e filo di stagno, Kapton, punte dei saldatori,
-- flussanti, pulizia, coating, imballaggio, ESD. Si comprano con gli ordini a fornitore e si richiamano scrivendo una parola ("lamina").
-- Codici NOSTRI (MC-<categoria>-<progressivo>); i codici dei fornitori stanno nella descrizione. Elenco iniziale ricavato dagli acquisti
-- 2022-2026 delle fatture dei fornitori di Fatture in Cloud (prezzi esclusi: si caricano dal file in Anagrafiche → Materiali).
CREATE TABLE IF NOT EXISTS materiali_consumo (
  id              serial PRIMARY KEY,
  codice          text NOT NULL UNIQUE,
  descrizione     text NOT NULL,
  categoria       text NOT NULL,
  um              text,
  note            text,
  attivo          boolean NOT NULL DEFAULT true,
  prezzo_acquisto numeric,
  prezzo_fornitore text,
  prezzo_quantita numeric,
  prezzo_data     date,
  prezzo_fonte    text,          -- 'fic' (caricato dal file) o 'manuale' (scritto in un ordine o qui): il caricamento non tocca i manuali
  prezzo_nota     text,
  creato_il       timestamptz NOT NULL DEFAULT now(),
  aggiornato_il   timestamptz NOT NULL DEFAULT now()
);

